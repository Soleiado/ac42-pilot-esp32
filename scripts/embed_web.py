"""Embed the single-page web UI into the firmware.

PlatformIO runs this script before the build.  Keeping the UI as a normal
index.html makes it easy to edit and to run against tools/mock_server.py.
"""

from pathlib import Path

try:  # PlatformIO / SCons
    Import("env")  # noqa: F821
    project = Path(env.subst("$PROJECT_DIR"))  # noqa: F821
except NameError:  # direct execution for a quick header regeneration
    project = Path(__file__).resolve().parents[1]

source = project / "src" / "web" / "index.html"
target = project / "src" / "generated" / "web_asset.h"

if not source.exists():
    raise SystemExit(f"Web UI not found: {source}")

data = source.read_bytes()
lines = []
for offset in range(0, len(data), 20):
    chunk = data[offset:offset + 20]
    lines.append("    " + ", ".join(f"0x{byte:02X}" for byte in chunk) + ",")

header = (
    "/* Generated by scripts/embed_web.py - do not edit. */\n"
    "#pragma once\n"
    "#include <pgmspace.h>\n\n"
    "static const unsigned char WEB_INDEX_HTML[] PROGMEM = {\n"
    + "\n".join(lines)
    + "\n};\n\n"
    + f"static const unsigned int WEB_INDEX_HTML_LEN = {len(data)}u;\n"
)

target.parent.mkdir(parents=True, exist_ok=True)
if not target.exists() or target.read_text(encoding="utf-8") != header:
    target.write_text(header, encoding="utf-8", newline="\n")
    print(f"Embedded web UI: {len(data)} bytes -> {target.relative_to(project)}")
